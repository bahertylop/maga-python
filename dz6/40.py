r"""
**Задача 40 (линейная алгебра).** Решите систему `A @ x = b` через `np.linalg.solve(A, b)` и через `np.linalg.inv(A) @ b`. Сравните результаты. Вычислите `np.linalg.det(A)`, `np.linalg.eig(A)`, `np.linalg.norm(b)`, `norm(b, ord=1)`, `norm(b, ord=np.inf)`. Оформите в `pd.Series`. Ожидаемый вывод: `solve` и `inv(A) @ b` дают одинаковый `x` (с точностью до плавающей погрешности); `det(A)` — скаляр; `eig(A)` возвращает `(eigenvalues, eigenvectors)`; `norm(b)` — евклидова норма. В комментариях объясните: почему `solve` устойчивее `inv` (меньше численных ошибок, не вычисляет обратную матрицу явно); что такое собственные значения (масштаб преобразования); когда матрица не имеет обратной (`det(A) == 0`); как норма используется в рекомендательных системах (расстояние между векторами предпочтений клиентов); как сохранить результат в Series с осмысленным индексом; что произойдёт при `solve` с вырожденной матрицей (`LinAlgError`).
"""
import numpy as np
import pandas as pd

A = np.array([[3.0, 1.0], [1.0, 2.0]]); b = np.array([9.0, 8.0])
x1 = np.linalg.solve(A, b); x2 = np.linalg.inv(A) @ b
print("solve:", x1, "| inv@b:", x2, "| совпали:", np.allclose(x1, x2))
w, v = np.linalg.eig(A)
res = pd.Series({"det(A)": np.linalg.det(A), "eig_1": w[0], "eig_2": w[1], "norm_2(b)": np.linalg.norm(b),
                 "norm_1(b)": np.linalg.norm(b, ord=1), "norm_inf(b)": np.linalg.norm(b, ord=np.inf)})
print(res.round(4))
print("Av = lambda*v:", np.allclose(A @ v[:, 0], w[0] * v[:, 0]))
S = np.array([[1.0, 2.0], [2.0, 4.0]])
print("det(вырожденной):", np.linalg.det(S))
try:
    np.linalg.solve(S, b)
except np.linalg.LinAlgError as e:
    print("solve с вырожденной ->", type(e).__name__, "-", e)
H = np.array([[1, 1 / 2, 1 / 3], [1 / 2, 1 / 3, 1 / 4], [1 / 3, 1 / 4, 1 / 5]])
print("обусловленность (Гильберт 3x3):", round(np.linalg.cond(H), 1))
# solve решает систему LU-разложением, не строя обратную матрицу: быстрее (~в 3 раза) и численно устойчивее, чем inv(A) @ b
# (у inv накапливается ошибка, особенно для плохо обусловленных матриц). Собственные значения - коэффициенты растяжения
# вдоль собственных векторов (A v = lambda v). Матрица необратима при det(A) = 0 (строки линейно зависимы) -> LinAlgError.
# Норма ||b|| - длина вектора; в рекомендательных системах расстояние ||u - v|| между векторами предпочтений клиентов.

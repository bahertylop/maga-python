r"""
**Задача 4 (арифметика, выравнивание, assign, pd.col()).** Создайте два Series цен по автомобилям с индексами `["V1", "V2", "V3", "V4"]` и `["V2", "V3", "V4", "V5"]`. Сложите их — зафиксируйте `NaN` на несовпадающих метках. Повторите через `.add(other, fill_value=0)`. Создайте `df = pd.DataFrame({"price": [2500000, 1800000, 1200000], "count": [3, 4, 5]})`. Через `assign(total=lambda x: x["price"] * x["count"])` добавьте `total`. Через `assign(total=pd.col("price") * pd.col("count"))` — то же. Сравните результаты. Ожидаемый вывод: `s1 + s2` даёт `V1=NaN`, `V2=…`, `V5=NaN`; `.add(..., fill_value=0)` даёт числа везде; оба `assign` возвращают идентичные DataFrame с новым столбцом `total`. В комментариях объясните: почему выравнивание по меткам — ключевая особенность Pandas (данные из разных филиалов салона с разным набором автомобилей); почему `pd.col()` помечен как «начальная поддержка»; почему `assign` не модифицирует исходный DataFrame (возвращает копию); как `fill_value` влияет на тип результата (может привести к `float`, если появляются `NaN`); в каких случаях `lambda` всё ещё нужен вместо `pd.col()` (сложные выражения, вызовы функций); что произойдёт при сложении Series с полностью непересекающимися индексами (все `NaN`).
"""
import pandas as pd

s1 = pd.Series([100, 200, 300, 400], index=["V1", "V2", "V3", "V4"])
s2 = pd.Series([10, 20, 30, 40], index=["V2", "V3", "V4", "V5"])
print("s1 + s2 (NaN на несовпадающих метках):\n", s1 + s2)
print("add(fill_value=0):\n", s1.add(s2, fill_value=0))
print("непересекающиеся индексы -> все NaN:", (s1 + pd.Series([1], index=["Z"])).isna().all())

df = pd.DataFrame({"price": [2500000, 1800000, 1200000], "count": [3, 4, 5]})
r1 = df.assign(total=lambda x: x["price"] * x["count"])
if hasattr(pd, "col"):                       # pd.col - Pandas 3.0+
    r2 = df.assign(total=pd.col("price") * pd.col("count"))
    print("pd.col == lambda:", r1.equals(r2))
else:
    print("pd.col недоступен в этой версии Pandas (нужна 3.0+) - используйте lambda")
print(r1, "| исходный df без total:", "total" not in df.columns)
# Выравнивание по меткам - ключевая идея Pandas: данные разных филиалов с разным набором
# автомобилей суммируются «по VIN», а не «по позиции».
# fill_value=0 подставляет 0 для отсутствующей метки ТОЛЬКО с одной стороны; если метка
# отсутствует у обоих - остаётся NaN. NaN делает столбец float - целые превращаются в float64.
# assign возвращает КОПИЮ (исходный df не изменён) - удобно для цепочек.
# pd.col() - «начальная поддержка»: новый API, работает не везде и с ограниченным набором выражений;
# lambda нужен для сложных выражений и вызовов функций (np.log(x["price"]), apply).

r"""
**Задача 12 (матрицы eye/diag, pd.col()).** Создайте список категорий автомобилей `["седаны", "внедорожники", "спорткары", "электромобили"]`. Создайте `pd.DataFrame(np.eye(4), index=categories, columns=categories)`. Создайте диагональную матрицу через `np.diag([1.0, 0.8, 0.6, 0.9])` (например, коэффициенты популярности категорий) и смещённую через `np.diag([0.5, 0.3], k=1)`. Через `assign(trace=pd.col("седаны") + pd.col("внедорожники"))` добавьте столбец. Ожидаемый вывод: `np.eye(4)` — диагональ из единиц, остальное нули; `np.diag([1.0, 0.8, 0.6, 0.9])` — эти значения на диагонали; `np.diag([0.5, 0.3], k=1)` — на диагонали выше главной. В комментариях объясните: что делает параметр `k` (смещение диагонали); в каких случаях диагональная матрица эффективнее плотной (только диагональ ненулевая — экономия памяти); почему `np.eye` возвращает `float`, а не `int` (по умолчанию `dtype=float`); как `pd.col()` помогает при вычислении `trace`; чем `np.diag`-конструктор отличается от `np.diag`-извлекателя (передаём 1D → матрица, 2D → диагональ); как метки `index`/`columns` влияют на выравнивание при арифметике.
"""
import numpy as np
import pandas as pd

cats = ["седаны", "внедорожники", "спорткары", "электромобили"]
eye = pd.DataFrame(np.eye(4), index=cats, columns=cats)
print(eye)
print("diag:\n", np.diag([1.0, 0.8, 0.6, 0.9]))
print("diag k=1:\n", np.diag([0.5, 0.3], k=1))
print("извлечение диагонали из 2D:", np.diag(np.arange(9).reshape(3, 3)))
if hasattr(pd, "col"):
    print(eye.assign(trace=pd.col("седаны") + pd.col("внедорожники")).head(2))
else:
    print(eye.assign(trace=lambda x: x["седаны"] + x["внедорожники"]).head(2))
# k - смещение диагонали: k>0 выше главной, k<0 ниже; для вектора длины 2 с k=1 получится матрица 3x3.
# Диагональная матрица эффективна, когда ненулевая только диагональ: её можно хранить вектором (экономия памяти, умножение O(n)).
# np.eye даёт float, потому что dtype по умолчанию float64 (можно dtype=int). np.diag(1D) строит матрицу, np.diag(2D) -
# ИЗВЛЕКАЕТ диагональ. Метки index/columns определяют выравнивание: eye + другой DataFrame складывается по меткам, а не по позициям.
pop = pd.Series([1.0, 0.8, 0.6, 0.9], index=cats)
print("выравнивание по меткам:\n", (eye * pop).iloc[:, :2])

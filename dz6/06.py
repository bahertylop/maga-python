r"""
**Задача 6 (DataFrame, доступ loc/iloc/at/iat).** Создайте `sales` 3×4 со случайными значениями продаж, индекс `["янв", "фев", "мар"]`, столбцы `["седаны", "внедорожники", "спорткары", "электромобили"]`. Выполните выборку: `sales.loc["фев"]`, `sales.iloc[1]`, `sales.loc["мар", "электромобили"]`, `sales.iloc[2, 2]`, `sales.at["янв", "седаны"]`, `sales.iat[0, 0]`. Выведите `type(...)` и `shape` каждой. Попробуйте `sales.loc["апр"]` и `sales.iloc[5]`. Ожидаемый вывод: `type(sales.loc["фев"])` — `Series` с `shape=(4,)`; `type(sales.loc["мар", "электромобили"])` — скаляр; `sales.loc["апр"]` → `KeyError`; `sales.iloc[5]` → `IndexError`. В комментариях объясните: почему `.at` быстрее `.loc` для одного значения (не создаёт промежуточные объекты); в каких случаях `[]` неоднозначен при числовом индексе (если индекс — целые числа, `df[1]` может быть и меткой, и позицией); почему `sales[["седаны"]]` возвращает DataFrame, а не Series (двойные скобки — список столбцов); как `.loc` обрабатывает срез по меткам в отличие от `.iloc` (включает конечную метку); что вернёт `sales.loc["янв":"мар"]` и почему конечная метка включается (семантика закрытого интервала у `.loc`).
"""
import numpy as np
import pandas as pd

rng = np.random.default_rng(6)
sales = pd.DataFrame(rng.integers(5, 50, (3, 4)), index=["янв", "фев", "мар"],
                     columns=["седаны", "внедорожники", "спорткары", "электромобили"])
print(sales)
for label, v in (('loc["фев"]', sales.loc["фев"]), ("iloc[1]", sales.iloc[1]),
                 ('loc["мар","электромобили"]', sales.loc["мар", "электромобили"]), ("iloc[2,2]", sales.iloc[2, 2]),
                 ('at["янв","седаны"]', sales.at["янв", "седаны"]), ("iat[0,0]", sales.iat[0, 0])):
    print(f"{label:28s} type={type(v).__name__:8s} shape={getattr(v, 'shape', '-')}")
for bad in (lambda: sales.loc["апр"], lambda: sales.iloc[5]):
    try:
        bad()
    except (KeyError, IndexError) as e:
        print(type(e).__name__, "->", e)
print("loc['янв':'мар'] (конец включается):", len(sales.loc["янв":"мар"]), "строки | iloc[0:2]:", len(sales.iloc[0:2]))
print("sales[['седаны']] ->", type(sales[["седаны"]]).__name__, "| sales['седаны'] ->", type(sales["седаны"]).__name__)
# .at/.iat - доступ к ОДНОМУ значению: без построения промежуточных объектов Series/DataFrame -> быстрее .loc/.iloc.
# df[1] при целочисленном индексе неоднозначен (метка или позиция?) - поэтому используйте .loc/.iloc.
# Двойные скобки [["col"]] - это СПИСОК столбцов -> DataFrame; одинарные -> Series.
# .loc-срез по меткам - закрытый интервал (конечная метка включается: у меток нет понятия «следующая»);
# .iloc - как обычный срез Python, правая граница не включается.

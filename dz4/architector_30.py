"""
Задача 30 (утиная типизация). В автосалоне есть разные объекты, у которых
есть метод describe() — автомобили, мотоциклы, грузовики, а может быть, и
что-то ещё, что появится в будущем. Напишите функцию describe_item(item),
которая вызывает метод describe() у любого объекта. Продемонстрируйте, что
функция работает не только с Car, но и с любым другим классом, у которого
есть describe() (например, классом Accessory), — без наследования от общего
родителя. Объясните принцип утиной типизации: «если это выглядит как утка,
плавает как утка и крякает как утка — это утка». Расскажите, как этот
принцип отличает Python от языков со строгой типизацией (Java, C++) и какие
у него минусы (ошибка видна только во время выполнения).
"""

from typing import Protocol


# Ни у одного класса нет общего родителя (кроме object)
class Car:
    def __init__(self, brand, model):
        self.brand, self.model = brand, model

    def describe(self):
        return f"Автомобиль {self.brand} {self.model}"


class Motorcycle:
    def describe(self):
        return "Мотоцикл Yamaha MT-07"


class Truck:
    def describe(self):
        return "Грузовик КАМАЗ 54901"


class Accessory:
    def __init__(self, name, price):
        self.name, self.price = name, price

    def describe(self):
        return f"Аксессуар: {self.name}, {self.price} ₽"


class Brochure:
    """Совсем не транспорт, но «крякает» так же — и тоже подходит."""

    def describe(self):
        return "Рекламный буклет салона"


class Customer:
    """У этого класса describe() нет."""

    name = "Иван"


def describe_item(item):
    # Функция не проверяет тип. Ей важно только одно — есть ли describe().
    print("•", item.describe())


items = [Car("Toyota", "Camry"), Motorcycle(), Truck(),
         Accessory("Коврики в салон", 3500), Brochure()]
for it in items:
    describe_item(it)

# Минус: ошибка видна только во время выполнения
print("\nПередаём объект без describe():")
try:
    describe_item(Customer())
except AttributeError as e:
    print("  AttributeError:", e)


# Варианты, как смягчить минус:
# 1) «Проще попросить прощения, чем разрешения» (EAFP) — try/except, как выше.
# 2) Проверка заранее (LBYL — «смотри, прежде чем прыгать»):
def describe_item_safe(item):
    if hasattr(item, "describe") and callable(item.describe):
        print("•", item.describe())
    else:
        print(f"• {type(item).__name__}: описание недоступно")


describe_item_safe(Customer())


# 3) Protocol из typing — «утиная типизация» с подсказками типов.
#    Классам по-прежнему не нужно ни от чего наследоваться, но анализатор
#    кода (mypy, PyCharm) найдёт ошибку ещё ДО запуска программы.
class Describable(Protocol):
    def describe(self) -> str: ...


def describe_typed(item: Describable) -> None:
    print("•", item.describe())


describe_typed(Accessory("Сигнализация", 25000))

# Принцип утиной типизации:
# «Если это выглядит как утка, плавает как утка и крякает как утка —
# значит, это утка». Python не спрашивает, КАКОГО КЛАССА объект, — он
# спрашивает, ЧТО объект УМЕЕТ. Если у объекта есть describe(), функция
# с ним работает. Это та же идея, что в задаче 4 с методом tax().
# Встроенный пример: len() работает с любым объектом, у которого есть
# __len__; цикл for — с любым объектом, у которого есть __iter__.
#
# Отличие от Java/C++:
# В языках со строгой статической типизацией функция принимает параметр
# конкретного типа: void describeItem(Describable item). Класс Accessory
# сможет туда попасть, только если явно объявит implements Describable
# (или наследуется от общего класса). Компилятор проверяет это заранее.
# В Python объявлять ничего не нужно — проверка «по факту» при вызове.
#
# Плюсы: меньше кода и формальностей, легко подставлять новые классы
# (в том числе чужие или тестовые заглушки), не нужны громоздкие иерархии.
# Минусы:
# - ошибка (нет метода, опечатка в имени) обнаружится только при выполнении
#   этой строки — возможно, уже у пользователя;
# - по сигнатуре функции не видно, какие методы нужны объекту, — это
#   приходится описывать в документации или через Protocol;
# - «совпадение по имени» ещё не гарантирует нужного смысла: метод
#   describe() может возвращать не строку, а что-то совсем другое.
# Поэтому в больших проектах утиную типизацию дополняют аннотациями типов,
# Protocol и тестами.

"""
**Задача 10 (единичная и диагональная матрицы).** Автосалон хранит матрицу корреляций между 4 характеристиками (цена, мощность, расход, объём). Создайте:
- `np.eye(4)`;
- `np.diag([1.0, 0.8, 0.6, 0.9])`;
- `np.diag([0.5, 0.3], k=1)`.

Выведите все три. **Что продемонстрировать:** `eye`, `diag` в обоих режимах, `k`. **Вопросы:** чем `eye` отличается от `identity`; что делает `k`; когда диагональная матрица лучше обычной; почему `eye` даёт `float`.
"""
import numpy as np

print("eye(4):\n", np.eye(4))
print("diag([1, .8, .6, .9]):\n", np.diag([1.0, 0.8, 0.6, 0.9]))
print("diag([.5, .3], k=1):\n", np.diag([0.5, 0.3], k=1))

# eye(N, M=None, k=0, dtype=float) - можно прямоугольную и со сдвигом диагонали;
# identity(n) - тонкая обёртка над eye: только квадратная единичная, без k.
# k - смещение диагонали: 0 главная, >0 выше, <0 ниже. diag(v, k=1) для вектора длины 2
# создаёт матрицу 3x3 (размер = len(v) + |k|).
# Диагональная матрица лучше «обычной», когда нужно задать масштабы/веса по осям или
# если почти все элементы нули: её можно хранить как вектор (np.diag(v) @ x == v * x).
# eye даёт float, потому что dtype по умолчанию float64 (можно: np.eye(4, dtype=int)).
print("v * x == diag(v) @ x:", np.allclose(np.diag([1, 2, 3, 4]) @ np.arange(4), np.array([1, 2, 3, 4]) * np.arange(4)))
print("eye dtype:", np.eye(2).dtype, "| eye(3, 4, k=1):\n", np.eye(3, 4, k=1))

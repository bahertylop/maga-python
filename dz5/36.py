"""
**Задача 36 (векторизация vs цикл).** Даны два массива из 10 000 000 цен. Реализуйте `a + b`:
- чистый Python-цикл `[a[i] + b[i] for i in range(n)]`;
- NumPy: `a + b`;
- NumPy с `out`: `np.add(a, b, out=result)`.

Замерьте время через `time.perf_counter()`. **Что продемонстрировать:** разницу скорости. **Вопросы:** почему NumPy быстрее; как непрерывная память и SIMD влияют; когда `out` даёт выигрыш; почему `a + b` создаёт массив, а `np.add(a, b, out=a)` — нет (когда это опасно); как векторизация связана с broadcasting.
"""
import time
import numpy as np

rng = np.random.default_rng(36)
n = 10_000_000
a, b = rng.random(n), rng.random(n)

t = time.perf_counter(); c = a + b; t_np = time.perf_counter() - t
res = np.empty(n)
t = time.perf_counter(); np.add(a, b, out=res); t_out = time.perf_counter() - t

# Чистый Python-цикл на 10M элементов потребовал бы ~2 ГБ на списки; измеряем на 1M и умножаем на 10 (линейная сложность)
m = 1_000_000
la, lb = a[:m].tolist(), b[:m].tolist()
t = time.perf_counter(); py = [la[i] + lb[i] for i in range(m)]; t_py = (time.perf_counter() - t) * (n / m)
print(f"Python-цикл (оценка для 10M): {t_py:.2f} с")
print(f"NumPy a + b                  : {t_np * 1e3:.1f} мс  (быстрее в ~{t_py / t_np:.0f} раз)")
print(f"NumPy np.add(..., out=)      : {t_out * 1e3:.1f} мс (без аллокации результата)")
print("корректность:", np.allclose(c[:m], py))
# NumPy быстрее, потому что цикл выполняется в скомпилированном C над НЕПРЕРЫВНЫМ блоком
# однотипных чисел (нет проверки типов и создания Python-объектов на каждый элемент),
# а процессор применяет SIMD (одна инструкция - несколько чисел) и хорошо использует кэш.
# out даёт выигрыш, когда результат переиспользуется много раз (нет повторной аллокации 80 МБ).
# a + b создаёт НОВЫЙ массив; np.add(a, b, out=a) пишет в a (экономит память), но ОПАСНО,
# если исходное a ещё нужно (данные затираются) или out пересекается с входами не
# элементно (для сложных ufunc/срезов). Векторизация использует broadcasting: операция по
# массивам разной формы без явных циклов.

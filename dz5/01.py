"""
**Задача 1 (создание массива, dtype, shape/size/ndim).** Автосалон ведёт учёт цен на 7 автомобилей: `[2500000, 1800000, 3200000, 950000, 4100000, 1450000, 2750000]` рублей. Создайте массив NumPy. Выведите `dtype`, `shape`, `size`, `ndim`. Дополнительно создайте такой же массив с `dtype=np.float32` и сравните `dtype`, `nbytes`. **Что продемонстрировать:** все атрибуты для обоих массивов. **Вопросы:** почему NumPy выбрал `int64`; чем `shape` отличается от `size`; почему `shape` у одномерного массива — кортеж `(7,)`, а не `(7)`; что вернёт `prices[7]` и почему.
"""
import numpy as np

prices = np.array([2500000, 1800000, 3200000, 950000, 4100000, 1450000, 2750000])
prices32 = np.array([2500000, 1800000, 3200000, 950000, 4100000, 1450000, 2750000], dtype=np.float32)

for name, a in (("int (по умолчанию)", prices), ("float32", prices32)):
    print(f"{name}: dtype={a.dtype}, shape={a.shape}, size={a.size}, ndim={a.ndim}, nbytes={a.nbytes}")

# int64: целые Python-числа NumPy по умолчанию кладёт в «платформенный» целочисленный тип
# (C long / intp) - на 64-битных ОС это int64; значения (до 4.1 млн) он вмещает с запасом.
# (На старых NumPy под Windows был int32.)
# shape - КОРТЕЖ длин по каждой оси ((3, 4) - 3 строки, 4 столбца), size - общее число
# элементов (произведение shape), ndim - число осей (= len(shape)).
# (7,) - кортеж из одного элемента: в Python одноэлементный кортеж пишется с запятой,
# а (7) - просто число 7 в скобках.
print("shape:", prices.shape, "| type:", type(prices.shape))
try:
    prices[7]                       # индексы 0..6 -> индекс 7 за границей
except IndexError as e:
    print("prices[7] ->", type(e).__name__, ":", e)
print("float32 вдвое экономнее по памяти:", prices.nbytes, "->", prices32.nbytes)

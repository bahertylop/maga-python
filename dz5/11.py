"""
**Задача 11 (индексация).** Дан массив цен `prices = np.array([2500000, 1800000, 3200000, 950000, 4100000, 1450000, 2750000])`. Получите:
- цену первого автомобиля (`prices[0]`);
- цену последнего (`prices[-1]`);
- цену третьего (`prices[2]`).

Дана матрица `sales` формы `(3, 4)` из задачи 6. Получите:
- продажи второй марки в январе (`sales[0, 1]`);
- всю строку за февраль (`sales[1]`);
- весь второй столбец (`sales[:, 1]`).

**Что продемонстрировать:** базовую индексацию 1D/2D. **Вопросы:** почему `sales[1]` — массив; что будет при `sales[5]`; почему отрицательные индексы работают; что вернёт `sales[-1, -1]`.
"""
import numpy as np

prices = np.array([2500000, 1800000, 3200000, 950000, 4100000, 1450000, 2750000])
sales = np.array([[120, 150, 90, 130], [110, 140, 100, 125], [130, 160, 95, 140]])
print("первая/последняя/третья:", prices[0], prices[-1], prices[2])
print("2-я марка в январе sales[0, 1]:", sales[0, 1])
print("строка за февраль  sales[1]   :", sales[1])
print("2-й столбец        sales[:, 1]:", sales[:, 1])
print("sales[-1, -1] =", sales[-1, -1], "(последняя строка, последний столбец)")
# sales[1] - массив: один индекс убирает ОДНУ ось (остаётся вектор из 4 чисел).
# sales[5] -> IndexError (в оси 0 только 3 элемента). Отрицательные индексы считаются с
# конца (-1 - последний): NumPy складывает их с длиной оси, i < 0 -> n + i.
try:
    sales[5]
except IndexError as e:
    print("sales[5] ->", e)

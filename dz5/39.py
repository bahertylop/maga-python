"""
**Задача 39 (полиномы и интерполяция).** Даны измерения количества продаж за 5 дней: `x = np.array([0, 1, 2, 3, 4])`, `y = np.array([12, 15, 11, 18, 14])`. Реализуйте:
- интерполяцию `np.interp` в `[0.5, 1.5, 2.5, 3.5]`;
- полином степени 2 через `np.polynomial.Polynomial.fit(x, y, deg=2)`;
- предсказание в тех же точках;
- сравните результаты.

Дополнительно: `np.interp` с `left=-1`, `right=-1`. **Что продемонстрировать:** интерполяцию и аппроксимацию. **Вопросы:** чем отличаются; почему полином высокой степени «выстреливает» (феномен Рунге); когда `np.interp` лучше; как интерполяция применяется для восстановления пропущенных дней в отчёте.
"""
import numpy as np

x = np.array([0, 1, 2, 3, 4]); y = np.array([12, 15, 11, 18, 14])
xi = np.array([0.5, 1.5, 2.5, 3.5])
lin = np.interp(xi, x, y)
poly = np.polynomial.Polynomial.fit(x, y, deg=2)
print("interp :", lin)
print("poly(2):", poly(xi).round(3), "| коэффициенты:", poly.convert().coef.round(3))
print("разница:", (lin - poly(xi)).round(3))
print("за пределами (left=-1, right=-1):", np.interp([-1, 2, 5], x, y, left=-1, right=-1))
# interp - кусочно-линейная ПРОХОДИТ через все точки (интерполяция). Полином степени 2 -
# аппроксимация: сглаживает данные и НЕ проходит через точки. Полином высокой степени
# через все точки (deg=len(x)-1) сильно колеблется между узлами (феномен Рунге). interp лучше,
# когда данные надёжны и нужно восстановить промежуточные значения без «выстрелов».
big = np.polynomial.Polynomial.fit(x, y, deg=4)
print("deg=4 проходит через точки:", np.allclose(big(x), y), "| между узлами:", big(np.array([0.25, 3.75])).round(2))
# Применение: восстановление пропущенных дней: valid = ~np.isnan(v); v[~valid] = np.interp(days[~valid], days[valid], v[valid])
v = np.array([10.0, np.nan, 14.0, np.nan, np.nan, 20.0]); d = np.arange(6); ok = ~np.isnan(v)
v[~ok] = np.interp(d[~ok], d[ok], v[ok])
print("заполнено:", v)

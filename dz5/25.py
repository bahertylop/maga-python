"""
**Задача 25 (сортировка).** Дан массив цен `prices = np.array([2500000, 1800000, 3200000, 950000, 4100000, 1450000, 2750000])`. Получите:
- по возрастанию (`np.sort(prices)`);
- по убыванию (`np.sort(-prices) * -1` или `np.sort(prices)[::-1]`);
- на месте через `prices.sort()`.

Дана `sales` формы `(3, 4)`. Отсортируйте:
- по умолчанию (`axis=-1`, по строкам);
- по `axis=0`;
- с `axis=None`.

**Что продемонстрировать:** сортировку по разным осям и на месте. **Вопросы:** чем `np.sort(arr)` отличается от `arr.sort()`; почему по умолчанию последняя ось; как обрабатывается NaN (добавьте `np.nan`); как выбрать стабильный алгоритм (`kind='stable'`).
"""
import numpy as np

prices = np.array([2500000, 1800000, 3200000, 950000, 4100000, 1450000, 2750000])
print("по возрастанию :", np.sort(prices))
print("по убыванию    :", np.sort(prices)[::-1], "| через -prices:", np.sort(-prices) * -1)
p = prices.copy(); p.sort()                  # на месте
print("на месте       :", p, "| исходный не тронут np.sort:", prices[:3])

sales = np.array([[120, 150, 90, 130], [110, 140, 100, 125], [130, 160, 95, 140]])
print("axis=-1 (по строкам):\n", np.sort(sales))
print("axis=0  (по столбцам):\n", np.sort(sales, axis=0))
print("axis=None (плоско)   :", np.sort(sales, axis=None))
# np.sort(arr) возвращает ОТСОРТИРОВАННУЮ КОПИЮ, arr.sort() сортирует на месте и возвращает
# None (экономит память). По умолчанию axis=-1 (последняя ось): сортируется каждая «строка».
# NaN в NumPy считаются большими любого числа - уходят в КОНЕЦ.
print("с NaN:", np.sort(np.array([3.0, np.nan, 1.0, 2.0])))
# kind='stable' - устойчивая сортировка: равные элементы сохраняют исходный порядок
# (важна при многоуровневой сортировке; реализована как timsort/radix).
print("stable argsort:", np.argsort(np.array([2, 1, 2, 1]), kind="stable"))

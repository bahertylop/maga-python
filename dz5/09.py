"""
**Задача 9 (arange vs linspace на практике).** Автосалон строит график продаж за 30 дней. Сравните:
- `np.arange(1, 31)`;
- `np.linspace(1, 30, 30)`.

Проверьте `len()`, первые и последние. Найдите случай, где `arange` даёт неверное количество: `np.arange(0, 1, 0.1)`. **Что продемонстрировать:** надёжность `linspace` против float-шага. **Вопросы:** почему `linspace` надёжнее; когда `arange` уместнее.
"""
import numpy as np

a = np.arange(1, 31)
b = np.linspace(1, 30, 30)
print("arange  : len", len(a), "первый/последний", a[0], a[-1], a.dtype)
print("linspace: len", len(b), "первый/последний", b[0], b[-1], b.dtype)

print("len(arange(0, 1, 0.1)) =", len(np.arange(0, 1, 0.1)))
print("arange(0, 1, 0.1)[-1] =", np.arange(0, 1, 0.1)[-1], "(1.0 не включена)")
x = np.arange(0.1, 0.4, 0.1)
print("arange(0.1, 0.4, 0.1):", x, "len", len(x), "- лишний элемент ~0.4, хотя stop=0.4 исключается")
print("len(arange(0, 2.1, 0.3)) =", len(np.arange(0, 2.1, 0.3)), "вместо 7")
# linspace надёжнее: число точек и ОБА конца заданы явно, шаг считается из них, и накопления
# ошибки нет. arange уместнее для целочисленных индексов/шагов (arange(n), arange(0, 100, 5)),

"""
**Задача 26 (`argsort` и топ-N).** Дан массив цен на 10 автомобилей: `prices = np.array([2500000, 1800000, 3200000, 950000, 4100000, 1450000, 2750000, 700000, 5000000, 2100000])`. Получите:
- индексы сортировки (`np.argsort(prices)`);
- применяя индексы — совпадает с `np.sort(prices)`.

Дополнительно: `models = np.array(["A","B","C","D","E","F","G","H","I","J"])`. Автомобили по возрастанию цены: `models[np.argsort(prices)]`. Топ-3 самых дорогих: `models[np.argsort(-prices)[:3]]`. **Что продемонстрировать:** сортировку параллельных массивов через `argsort`. **Вопросы:** зачем `argsort` при наличии `sort`; как сортировать параллельные массивы; почему `argsort(-prices)` даёт убывание; что такое непрямая сортировка.
"""
import numpy as np

prices = np.array([2500000, 1800000, 3200000, 950000, 4100000, 1450000, 2750000, 700000, 5000000, 2100000])
models = np.array(list("ABCDEFGHIJ"))
idx = np.argsort(prices)
print("argsort:", idx)
print("prices[idx] == sort:", np.array_equal(prices[idx], np.sort(prices)))
print("по возрастанию цены:", models[idx])
print("топ-3 дорогих     :", models[np.argsort(-prices)[:3]], "| альтернатива:", models[idx[::-1][:3]])
# argsort возвращает ИНДЕКСЫ, которые упорядочили бы массив (непрямая сортировка). Нужна,
# когда есть параллельные массивы: один и тот же idx применяется к models, prices,
# years - строки остаются согласованными (sort цен сам по себе связь с моделями теряет).
# argsort(-prices) даёт убывание: у отрицательных чисел порядок обращается
# (для беззнаковых типов так нельзя - используйте idx[::-1]).

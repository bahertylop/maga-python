"""
**Задача 12 (срезы).** Дан массив цен на 30 автомобилей: `prices = np.arange(30) * 100000 + 500000`. Получите:
- первые 7 (`prices[:7]`);
- последние 7 (`prices[-7:]`);
- с 10-го по 20-й (`prices[10:20]`);
- каждый второй (`prices[::2]`);
- в обратном порядке (`prices[::-1]`).

Дана `sales` формы `(3, 4)`. Получите:
- первые две строки (`sales[:2, :]`);
- второй и третий столбцы (`sales[:, 1:3]`);
- подматрицу `2×2` (`sales[:2, :2]`).

**Что продемонстрировать:** все виды срезов. **Вопросы:** включается ли правая граница; что делает `[::-1]`; почему срез — view; как проверить `prices[:7].base is prices`.
"""
import numpy as np

prices = np.arange(30) * 100000 + 500000
print("первые 7      :", prices[:7])
print("последние 7   :", prices[-7:])
print("с 10 по 20    :", prices[10:20])
print("каждый второй :", prices[::2])
print("обратный      :", prices[::-1][:5], "...")
sales = np.array([[120, 150, 90, 130], [110, 140, 100, 125], [130, 160, 95, 140]])
print("sales[:2, :]  :\n", sales[:2, :])
print("sales[:, 1:3]:\n", sales[:, 1:3])
print("sales[:2, :2]:\n", sales[:2, :2])
# Правая граница НЕ включается: [10:20] даёт индексы 10..19. [::-1] - шаг -1: обратный порядок.
# Срез - VIEW (вид на те же данные, без копирования): быстро и экономно по памяти, но
# изменение среза меняет исходник.
v = prices[:7]
print("v.base is prices:", v.base is prices, "| shares_memory:", np.shares_memory(prices, v))

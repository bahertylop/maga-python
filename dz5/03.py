"""
**Задача 3 (арифметические операции).** Даны цены четырёх автомобилей `[2500000, 1800000, 3200000, 950000]` рублей. Одной строкой без циклов:
- увеличьте все цены на 7% (инфляция);
- посчитайте цены со скидкой 10%;
- возведите цены в квадрат (условно);
- прибавьте к каждой цене 50 000 рублей (доп. оборудование).

Выведите массивы. **Что продемонстрировать:** поэлементность операций. **Вопросы:** почему `prices * 1.07` даёт поэлементное умножение, а не повторение, как у списков; что произойдёт с `dtype` после `prices * 1.07`; что случится при `prices + "руб."`.
"""
import numpy as np

prices = np.array([2500000, 1800000, 3200000, 950000])
print("+7%         :", prices * 1.07)
print("скидка 10%  :", prices * 0.9)
print("квадрат     :", prices ** 2)
print("+50 000     :", prices + 50_000)

# Поэлементность: операторы массива векторизованы - применяются к КАЖДОМУ элементу
# (в списках `lst * 2` - повторение списка, `lst * 1.07` - ошибка).
print("list * 2    :", [1, 2] * 2)
# Умножение int-массива на 1.07 (float) -> результат float64: NumPy поднимает тип
# до «общего» (type promotion), чтобы не потерять дробную часть.
print("dtype до/после:", prices.dtype, "->", (prices * 1.07).dtype)
try:
    prices + "руб."                 # строка и число не имеют общего ufunc add -> ошибка
except Exception as e:
    print("prices + 'руб.' ->", type(e).__name__)

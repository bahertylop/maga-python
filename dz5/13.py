"""
**Задача 13 (логическая индексация).** Дан массив цен `prices = np.array([2500000, 1800000, 3200000, 950000, 4100000, 1450000, 2750000, 700000, 5000000])`. Получите:
- премиум-автомобили (дороже 3 000 000) (`prices[prices > 3000000]`);
- бюджетные (дешевле 1 500 000) (`prices[prices < 1500000]`);
- средний сегмент 1.5–3 млн (`prices[(prices >= 1500000) & (prices <= 3000000)]`);
- очень дешёвые или очень дорогие (`prices[(prices < 800000) | (prices > 4000000)]`).

Дополнительно: замените все цены ниже 800 000 на 800 000 (`prices[prices < 800000] = 800000`). **Что продемонстрировать:** фильтрацию и замену. **Вопросы:** почему нужны скобки; почему нельзя `and`/`or`; почему возвращается копия; как `np.where` мог бы заменить последнюю операцию.
"""
import numpy as np

prices = np.array([2500000, 1800000, 3200000, 950000, 4100000, 1450000, 2750000, 700000, 5000000])
print("премиум  >3M      :", prices[prices > 3_000_000])
print("бюджет   <1.5M    :", prices[prices < 1_500_000])
print("средний 1.5-3M    :", prices[(prices >= 1_500_000) & (prices <= 3_000_000)])
print("<800k или >4M     :", prices[(prices < 800_000) | (prices > 4_000_000)])

# Скобки обязательны: приоритет у & и | выше, чем у сравнений, поэтому
# prices >= a & prices <= b разберётся как prices >= (a & prices) <= b - ошибка.
# and/or работают с ОДНИМ булевым значением (неоднозначно для массива: ValueError "truth value...
# is ambiguous"); & и | - поэлементные.
# Фильтрация маской возвращает КОПИЮ (элементы выбираются по произвольному шаблону,
# общий буфер невозможен). Присваивание же prices[маска] = x меняет исходный массив.
copy_prices = prices.copy()
copy_prices[copy_prices < 800_000] = 800_000
print("после замены:", copy_prices)
# np.where делает то же без изменения исходника: np.where(prices < 800000, 800000, prices)
print("where:", np.where(prices < 800_000, 800_000, prices))
try:
    prices[(prices > 1) and (prices < 5)]
except ValueError as e:
    print("and ->", str(e)[:60], "...")

"""
**Задача 14 (fancy indexing).** Дан массив цен `prices = np.array([2500000, 1800000, 3200000, 950000, 4100000, 1450000, 2750000])`. Получите:
- цены автомобилей 0, 2, 5 (`prices[[0, 2, 5]]`);
- те же в обратном порядке (`prices[[5, 2, 0]]`);
- с повторениями (`prices[[0, 0, 1, 1, 2]]`).

Дана `sales` формы `(3, 4)`. Получите:
- строки 0 и 2 (`sales[[0, 2]]`);
- столбцы 1 и 3 (`sales[:, [1, 3]]`);
- диагональные (`sales[[0, 1, 2], [0, 1, 2]]`);
- подматрицу через `np.ix_([0, 2], [1, 3])` — сравните с `sales[[0, 2], [1, 3]]`.

**Что продемонстрировать:** выборку по массивам индексов и разницу `np.ix_`. **Вопросы:** чем fancy отличается от среза; почему всегда копия; зачем `np.ix_`; что при выходе за границу.
"""
import numpy as np

prices = np.array([2500000, 1800000, 3200000, 950000, 4100000, 1450000, 2750000])
print("[0, 2, 5]      :", prices[[0, 2, 5]])
print("[5, 2, 0]      :", prices[[5, 2, 0]])
print("с повторами    :", prices[[0, 0, 1, 1, 2]])
sales = np.array([[120, 150, 90, 130], [110, 140, 100, 125], [130, 160, 95, 140]])
print("строки 0 и 2   :\n", sales[[0, 2]])
print("столбцы 1 и 3  :\n", sales[:, [1, 3]])
print("диагональ      :", sales[[0, 1, 2], [0, 1, 2]])
print("sales[[0,2],[1,3]] (пары (0,1),(2,3)):", sales[[0, 2], [1, 3]])
print("np.ix_([0,2],[1,3]) (подматрица 2x2):\n", sales[np.ix_([0, 2], [1, 3])])
# fancy (по массивам индексов) vs срез: можно брать любые позиции в любом порядке и с
# повторами; результат ВСЕГДА копия (элементы могут лежать в памяти вразброс, view
# с постоянным шагом невозможен). Два списка индексов - это ПАРЫ (i, j), а не
# «декартово произведение»; для подматрицы строки×столбцы нужен np.ix_.
try:
    prices[[0, 99]]
except IndexError as e:
    print("выход за границу ->", e)
print("fancy - копия:", prices[[0, 2]].base is None)

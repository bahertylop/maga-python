"""
**Задача 4 (zeros/ones/full/empty).** Автосалон выделяет буферы:
- массив из 30 нулей — будущие ежедневные продажи;
- массив из 12 единиц — веса месяцев;
- массив из 5 значений `-1` — маркер «нет цены»;
- пустой массив из 3 элементов — буфер, заполните `[2500000, 1800000, 3200000]`.

Для каждого выведите результат и `dtype`. **Что продемонстрировать:** четыре функции и их вывод. **Вопросы:** зачем нужен `np.empty`; почему `np.zeros(5)` даёт `float64`, а не `int64`; в каком случае `np.empty` быстрее `np.zeros`.
"""
import numpy as np

daily = np.zeros(30)                     # 30 нулей (будущие продажи)
weights = np.ones(12)                    # 12 единиц
no_price = np.full(5, -1)                # 5 значений -1 (маркер «нет цены»)
buf = np.empty(3, dtype=np.int64)        # буфер БЕЗ инициализации
buf[:] = [2500000, 1800000, 3200000]     # заполняем сами

for name, a in (("zeros", daily), ("ones", weights), ("full(-1)", no_price), ("empty+fill", buf)):
    print(f"{name:11s} dtype={a.dtype}  {a[:5]}")

# np.empty выделяет память и НЕ заполняет её (там мусор от прошлого использования):
# экономит время на инициализацию, когда всё равно сразу перезапишете весь массив.
# Поэтому empty быстрее zeros, если массив гарантированно будет полностью заполнен
# (результат вычислений, out=...). Читать значения empty до записи нельзя.
# zeros даёт float64, потому что dtype по умолчанию у функций создания - float64.
# Для целых надо указать dtype=int (или np.full(.., -1) выведет int из значения).
print("zeros(5, dtype=int):", np.zeros(5, dtype=int).dtype)
print("empty (мусор до записи):", np.empty(3))

"""
**Задача 2 (подбор dtype под задачу).** В автосалоне три вида данных:
- цены автомобилей (от 500 000 до 50 000 000 рублей);
- год выпуска (1950–2025);
- объём двигателя в литрах (1.0–8.0 с одним знаком после запятой).

Для каждого создайте массив и подберите **минимальный** `dtype` без переполнения. Выведите `dtype`, `itemsize`, `nbytes`. Дополнительно проверьте: что произойдёт с `np.array([100, 200, 250], dtype=np.uint8) + 10`? **Что продемонстрировать:** корректный выбор типа и пример переполнения. **Вопросы:** почему для цен не стоит брать `uint8`; почему для года хватает `uint16`; как связаны `dtype`, `itemsize` и `nbytes`; почему NumPy не выбрасывает исключение при переполнении.
"""
import numpy as np

# Цены 500_000..50_000_000: не влезают в uint8 (0..255) и uint16 (0..65535).
# Минимум без переполнения: uint32 (до ~4.29 млрд) - 4 байта; цены неотрицательны.
prices = np.array([500_000, 12_000_000, 50_000_000], dtype=np.uint32)
# Годы 1950..2025: больше 255, но меньше 65535 -> uint16 (2 байта).
years = np.array([1950, 1999, 2025], dtype=np.uint16)
# Объём 1.0..8.0 с одним знаком: float16 (2 байта) хватает (точность ~3 знака).
# Ещё компактнее - хранить десятые доли как uint8 (10..80) и делить на 10 при чтении.
volume = np.array([1.0, 2.5, 8.0], dtype=np.float16)
volume_tenths = np.array([10, 25, 80], dtype=np.uint8)

for name, a in (("цены uint32", prices), ("годы uint16", years), ("объём float16", volume),
                ("объём в десятых uint8", volume_tenths)):
    print(f"{name}: dtype={a.dtype}, itemsize={a.itemsize}, nbytes={a.nbytes}")
# nbytes = size * itemsize: itemsize - байт на элемент (определяется dtype).

# Переполнение: 250 + 10 = 260 > 255 -> NumPy молча «заворачивает» по модулю 256
r = np.array([100, 200, 250], dtype=np.uint8) + 10
print("uint8 + 10 =", r, "(250+10=260 -> 4)")
# Почему не ошибка: целочисленная арифметика в NumPy - как в C (быстро, без проверок
# на каждый элемент); проверки замедлили бы векторные операции. Ответственность за
# выбор dtype на программисте (для безопасности - более широкий тип или np.errstate/проверки).
# Для цен uint8 не годится: максимальная цена в миллионы, а тип вмещает только 0..255.
print("iinfo uint32:", np.iinfo(np.uint32).max, "| uint16:", np.iinfo(np.uint16).max)

print("sales + offset:\n", sales + offset)
offset_col = np.array([[100], [200], [300]])          # (3, 1)
print("sales + offset_col:\n", sales + offset_col)
print("sales + скаляр:\n", sales + 7)
wrong = np.array([1, 2, 3])                           # (3,)
try:
    sales + wrong
except ValueError as e:
    print("ошибка:", e)

"""
**Задача 6 (двумерные массивы, форма).** Автосалон хранит продажи за 3 месяца по 4 маркам:
```python
sales = np.array([
    [120, 150, 90, 130],   # январь: Toyota, BMW, Kia, Hyundai
    [110, 140, 100, 125],  # февраль
    [130, 160, 95, 140],   # март
])
```
Выведите `shape`, `ndim`, `size`, `nbytes`. Получите:
- продажи в феврале (`sales[1]`);
- продажи третьей марки в марте (`sales[2, 2]`);
- весь второй столбец (`sales[:, 1]`).

**Что продемонстрировать:** доступ к строкам, элементам, столбцам. **Вопросы:** почему `sales[1]` — одномерный массив; что произойдёт при `sales[5]`; почему `sales[1, 2]` эффективнее, чем `sales[1][2]`.
"""
import numpy as np

sales = np.array([
    [120, 150, 90, 130],   # январь: Toyota, BMW, Kia, Hyundai
    [110, 140, 100, 125],  # февраль
    [130, 160, 95, 140],   # март
])
print("shape", sales.shape, "ndim", sales.ndim, "size", sales.size, "nbytes", sales.nbytes)
print("февраль      sales[1]    :", sales[1])
print("Kia в марте  sales[2, 2] :", sales[2, 2])
print("2-й столбец  sales[:, 1] :", sales[:, 1])

# sales[1] - ОДНОМЕРНЫЙ массив: индексирование одним числом убирает первую ось
# (строка матрицы - это вектор из 4 чисел).
print("sales[1].shape:", sales[1].shape)
try:
    sales[5]                       # в оси 0 только 3 строки -> IndexError
except IndexError as e:
    print("sales[5] ->", e)
# sales[1, 2] - один запрос к массиву сразу по двум осям: прямое вычисление смещения.
# sales[1][2] - сначала создаётся промежуточный объект-массив sales[1], затем он
# индексируется: лишняя аллокация и накладные расходы Python.

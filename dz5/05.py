"""
**Задача 5 (arange, linspace).** Автосалон строит сетки:
- `np.arange(2015, 2026)` — годы выпуска 2015…2025;
- `np.arange(0, 5000001, 500000)` — ценовые пороги от 0 до 5 000 000;
- `np.linspace(500000, 5000000, 10)` — 10 равномерных точек между ценой 500 тыс. и 5 млн;
- `np.linspace(0, 1, 5)` — 5 точек для нормировки.

Для каждого выведите результат и `len()`. Проверьте `len(np.arange(0, 1, 0.1))` — 10? **Что продемонстрировать:** разницу `arange` vs `linspace`. **Вопросы:** чем отличаются функции; почему `arange` с float-шагом опасен; когда что выбирать.
"""
import numpy as np

years = np.arange(2015, 2026)
thresholds = np.arange(0, 5_000_001, 500_000)
pts = np.linspace(500_000, 5_000_000, 10)
norm = np.linspace(0, 1, 5)
for name, a in (("arange годы", years), ("arange пороги", thresholds), ("linspace 10 точек", pts), ("linspace 0..1", norm)):
    print(f"{name:18s} len={len(a):2d}  {a}")

print("len(arange(0, 1, 0.1)) =", len(np.arange(0, 1, 0.1)), "(10 - верно, но это удача)")

# arange(start, stop, step): шаг задаём мы, stop НЕ включается, число точек выводится из
# (stop-start)/step. linspace(start, stop, num): число точек задаём мы, концы ВКЛЮЧЕНЫ
# (endpoint=True), шаг вычисляется.
# Float-шаг опасен: 0.1 не представим точно в двоичном виде, (stop-start)/step даёт
# 2.9999999999999996 или 3.0000000000000004 - число элементов может «плыть» на 1, и
# последний элемент может неожиданно попасть/не попасть в диапазон.
x = np.arange(0.1, 0.4, 0.1)
print("arange(0.1, 0.4, 0.1) =", x, "-> len", len(x), "(ожидали 3: 0.1, 0.2, 0.3; stop НЕ включается!)")
print("arange(0, 2.1, 0.3) len =", len(np.arange(0, 2.1, 0.3)), "(точная математика даёт 7)")
print("linspace(0.1, 0.3, 3) =", np.linspace(0.1, 0.3, 3), "- всегда ровно 3 точки")
# Выбор: целые шаги - arange; нужно ровно N точек или включить правый конец - linspace.

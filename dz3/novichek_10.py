"""
Задача 10 (имитация перегрузки). Менеджеру автосалона нужен метод для
оформления заказов, который мог бы работать в разных ситуациях: иногда
известен только автомобиль, иногда автомобиль и покупатель, иногда ещё и
дополнительные опции. Важно понимать: в Python нет классической перегрузки
методов, как в Java или C++, потому что один метод — это один
объект-функция. Поэтому «перегрузку» имитируют через значения по умолчанию
и *args. Создайте класс OrderDesk с методом place(car, buyer=None,
extras=None), который в зависимости от переданных аргументов выводит одно
из трёх сообщений: «Оформлен заказ на автомобиль: », «Автомобиль оформлен
для » или «Автомобиль для с опциями: ». Продемонстрируйте все три варианта
вызова. Объясните в комментариях, почему в Python выбрали именно такой
подход.
"""


class OrderDesk:
    def place(self, car, buyer=None, extras=None):
        # Один метод, а поведение зависит от того, какие аргументы переданы.
        if buyer is None:
            print(f"Оформлен заказ на автомобиль: {car}")
        elif not extras:
            print(f"Автомобиль {car} оформлен для {buyer}")
        else:
            print(f"Автомобиль {car} для {buyer} с опциями: {', '.join(extras)}")

    # Вариант с *args: опции можно перечислить просто через запятую
    def place_with_args(self, car, buyer=None, *extras):
        self.place(car, buyer, list(extras))


desk = OrderDesk()

desk.place("Toyota Camry")
desk.place("Toyota Camry", "Иван Петров")
desk.place("Toyota Camry", "Иван Петров", ["подогрев сидений", "камера заднего вида"])

print("--- то же через *args ---")
desk.place_with_args("Kia Rio", "Анна Смирнова", "тонировка", "коврики")

# Почему в Python выбрали такой подход:
# 1. В Python функция — это объект, и в классе по одному имени хранится
#    ровно один объект. Второе определение с тем же именем перезапишет
#    первое, поэтому несколько версий метода просто негде хранить.
# 2. Python — язык с динамической типизацией: типы аргументов не
#    объявляются, а значит, выбрать «нужную» версию по типам при
#    компиляции невозможно.
# 3. Значения по умолчанию, *args и **kwargs решают ту же задачу проще:
#    вся логика в одном месте, нет дублирования кода и не нужно искать,
#    какая из нескольких версий метода сработает.
# (Для перегрузки по типу первого аргумента есть functools.singledispatch,
#  но это уже отдельный инструмент.)

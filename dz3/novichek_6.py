"""
Задача 6 (статические методы). Автосалону нужна утилита для проверки
государственных номеров, которая не зависит от конкретного объекта и может
вызываться сама по себе. Создайте класс AutoUtils со статическим методом
is_valid_plate(plate), который возвращает True, если строка начинается с
букв «AB» и её длина равна 7, и False — в противном случае. Вызовите метод,
не создавая объекта класса, — напрямую через имя класса:
AutoUtils.is_valid_plate("AB12345"). Поясните, чем статический метод
отличается от обычного и от классового (см. задачу 15) и когда его стоит
использовать.
"""


class AutoUtils:
    @staticmethod
    def is_valid_plate(plate):
        # У статического метода нет ни self, ни cls: он не знает ни об объекте,
        # ни о классе. Это обычная функция, «положенная» в класс по смыслу.
        return isinstance(plate, str) and plate.startswith("AB") and len(plate) == 7


# Вызов без создания объекта — прямо через имя класса
print(AutoUtils.is_valid_plate("AB12345"))   # True
print(AutoUtils.is_valid_plate("AB1234"))    # False — длина 6
print(AutoUtils.is_valid_plate("CD12345"))   # False — начинается не с AB
print(AutoUtils.is_valid_plate("AB123456"))  # False — длина 8

# Отличия:
# - Обычный метод получает self — конкретный объект — и работает с его
#   данными. Вызывать его нужно у объекта: car.info().
# - Классовый метод (@classmethod) получает cls — сам класс — и работает
#   с данными класса, часто используется как альтернативный конструктор
#   (подробнее — задача 15).
# - Статический метод (@staticmethod) не получает ни self, ни cls и не
#   имеет доступа ни к объекту, ни к классу.
#
# Когда использовать статический метод: если функция логически относится
# к классу (проверка номера — «автомобильная» утилита), но ей не нужны
# данные объекта или класса. Так код группируется по смыслу.

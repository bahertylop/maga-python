"""
Задача 2 (инкапсуляция). У каждого автомобиля есть VIN-номер, который нельзя
менять или читать напрямую. Создайте класс CarPassport, в котором VIN-номер
хранится в приватном поле __vin. Реализуйте метод set_vin(value),
предназначенный только для установки номера при постановке на учёт, и метод
get_vin() для чтения значения. Повторная попытка изменить номер после
постановки на учёт должна игнорироваться, а не вызывать ошибку.
Продемонстрируйте работу класса: создайте паспорт, установите VIN, попробуйте
изменить его ещё раз и убедитесь, что значение осталось прежним.
Дополнительно покажите, что снаружи нельзя напрямую прочитать passport.__vin —
будет ошибка AttributeError, но через name mangling
(passport._CarPassport__vin) доступ всё же существует. Объясните в
комментариях, почему «игнорировать без ошибки» иногда лучше, чем выбрасывать
исключение, и почему приватность в Python — это скорее договорённость, чем
жёсткая защита.
"""


class CarPassport:
    def __init__(self):
        self.__vin = None  # приватное поле: VIN ещё не установлен

    def set_vin(self, value):
        # Устанавливаем номер только один раз — при постановке на учёт.
        # Повторные попытки молча игнорируются.
        #
        # Почему «игнорировать без ошибки» иногда лучше исключения:
        # - программа не падает из-за безобидной повторной операции
        #   (например, форму постановки на учёт отправили дважды);
        # - вызывающему коду не нужно оборачивать каждый вызов в try/except;
        # - важный инвариант (VIN неизменен) всё равно соблюдается.
        # Минус: ошибку в логике можно не заметить, поэтому такой подход
        # уместен там, где повтор действия действительно не страшен.
        if self.__vin is None:
            self.__vin = value

    def get_vin(self):
        return self.__vin


passport = CarPassport()
passport.set_vin("XTA21099012345678")
print("VIN после постановки на учёт:", passport.get_vin())

passport.set_vin("JTDBR32E720123456")  # попытка изменить — игнорируется
print("VIN после попытки изменить:  ", passport.get_vin())

# Прямой доступ к приватному полю снаружи не работает:
try:
    print(passport.__vin)
except AttributeError as e:
    print("Ошибка AttributeError:", e)

# Но через name mangling доступ всё же есть.
# Python просто переименовывает __vin в _CarPassport__vin внутри объекта.
print("Через name mangling:", passport._CarPassport__vin)

# Почему приватность в Python — договорённость, а не жёсткая защита:
# двойное подчёркивание лишь меняет имя атрибута, чтобы его нельзя было
# случайно задеть снаружи или перезаписать в наследнике. Намеренно
# обратиться к полю всё равно можно. Python исходит из принципа
# «мы все здесь взрослые люди»: программист видит знак «не трогать»
# и сам отвечает за то, если его нарушит.

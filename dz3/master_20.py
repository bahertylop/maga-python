"""
Задача 20 (@dataclass и миксин). Класс Car содержит только данные и простые
методы — его удобно переписать через декоратор @dataclass, чтобы не писать
вручную конструктор, __repr__ и __eq__. Перепишите класс Car через
@dataclass и сравните с версией из задачи 1. Дополнительно создайте миксин
LoggableMixin с методом log(), который выводит имя класса и текущее время
(используйте from datetime import datetime). Подключите миксин к классу Car
через множественное наследование, причём миксин должен идти первым в списке
родителей: class Car(LoggableMixin): .... Продемонстрируйте работу миксина.
Объясните, что такое миксин и чем он отличается от обычного родительского
класса: миксин — это «примесь» с одной узкой функциональностью, он не
предназначен для самостоятельного использования и обычно не имеет
собственного состояния.
"""

from dataclasses import dataclass
from datetime import datetime


# ---------- Версия из задачи 1: всё пишем вручную ----------
class OldCar:
    def __init__(self, brand, model, price):
        self.brand = brand
        self.model = model
        self.price = price

    def info(self):
        price_str = f"{self.price:,}".replace(",", " ")
        return f"{self.brand} — {self.model}, {price_str} ₽"
    # __repr__ и __eq__ не написаны — придётся добавлять самим


# ---------- Миксин ----------
class LoggableMixin:
    """Примесь: добавляет любому классу умение писать в лог.
    Своих полей и конструктора нет — только одно узкое поведение."""

    def log(self, message=""):
        now = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        print(f"[{now}] {type(self).__name__}: {message}")


# ---------- Новая версия через @dataclass + миксин ----------
@dataclass
class Car(LoggableMixin):
    brand: str
    model: str
    price: int

    def info(self):
        price_str = f"{self.price:,}".replace(",", " ")
        return f"{self.brand} — {self.model}, {price_str} ₽"


# Миксин можно «подмешать» в любой другой класс
@dataclass
class Buyer(LoggableMixin):
    name: str


old1, old2 = OldCar("Toyota", "Camry", 2500000), OldCar("Toyota", "Camry", 2500000)
new1, new2 = Car("Toyota", "Camry", 2500000), Car("Toyota", "Camry", 2500000)

print("Обычный класс (задача 1):")
print("  repr:", repr(old1))           # нечитаемый адрес в памяти
print("  old1 == old2:", old1 == old2)  # False — сравниваются адреса
print("  info:", old1.info())

print("@dataclass:")
print("  repr:", repr(new1))            # Car(brand='Toyota', model='Camry', price=2500000)
print("  new1 == new2:", new1 == new2)  # True — сравниваются поля
print("  info:", new1.info())

print("\nРабота миксина:")
new1.log("автомобиль добавлен в каталог")
Buyer("Иван Петров").log("покупатель зарегистрирован")
print("MRO Car:", [c.__name__ for c in Car.__mro__])

# Сравнение с задачей 1:
# @dataclass по аннотациям полей сам генерирует __init__, __repr__ и __eq__.
# Кода меньше, а возможностей больше: читаемый вывод, сравнение по
# значениям. Дополнительно можно включить order=True (сравнение < >),
# frozen=True (неизменяемость), задать значения по умолчанию.
#
# Что такое миксин:
# «примесь» — маленький класс с одной узкой функциональностью (здесь —
# логирование), который подключается к другим классам через наследование.
# Отличия от обычного родителя:
# - обычный родитель описывает, ЧЕМ является объект («Car — это Vehicle»),
#   а миксин добавляет УМЕНИЕ («Car умеет логировать»);
# - миксин не предназначен для самостоятельного использования —
#   объект LoggableMixin() сам по себе бессмыслен;
# - у миксина обычно нет собственного состояния и конструктора, поэтому
#   он не конфликтует с полями и __init__ основного класса;
# - миксин ставят первым в списке родителей, чтобы его методы стояли
#   в MRO раньше методов основной иерархии.

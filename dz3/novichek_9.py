"""
Задача 9 (переопределение методов). В автосалоне есть базовый класс
AutoItem с методом get_info(), который возвращает строку «Транспорт
автосалона». Унаследуйте от него класс Car и переопределите метод
get_info() так, чтобы он возвращал строку «Автомобиль: <марка> <модель>».
Создайте объект класса Car, вызовите метод get_info() и убедитесь, что
используется версия из дочернего класса, а не из родительского. Объясните
разницу между переопределением (override) и перегрузкой (overload) — и
почему в Python «настоящей» перегрузки методов нет.
"""


class AutoItem:
    def get_info(self):
        return "Транспорт автосалона"


class Car(AutoItem):
    def __init__(self, brand, model):
        self.brand = brand
        self.model = model

    def get_info(self):  # переопределение (override) метода родителя
        return f"Автомобиль: {self.brand} {self.model}"


car = Car("Toyota", "Camry")
print("Car.get_info():     ", car.get_info())            # версия из Car
print("AutoItem.get_info():", AutoItem.get_info(car))    # версия родителя для сравнения
print("Метод взят из класса:", type(car).get_info.__qualname__)  # Car.get_info

# Override (переопределение) — наследник заменяет метод родителя своей
# версией с тем же именем. Какую версию вызвать, решается по классу объекта.
#
# Overload (перегрузка) — несколько методов с одним именем, но разными
# параметрами в ОДНОМ классе (как в Java/C++: print(int), print(String)).
#
# Почему в Python нет «настоящей» перегрузки: методы хранятся в словаре
# класса по имени. Если объявить второй def с тем же именем, он просто
# перезапишет первый — останется только последний вариант.
# Поэтому перегрузку имитируют аргументами по умолчанию, *args, **kwargs
# (см. задачу 10).


class Demo:
    def hello(self):
        return "без аргументов"

    def hello(self, name):  # перезаписывает предыдущий hello
        return f"с аргументом {name}"


try:
    Demo().hello()
except TypeError as e:
    print("Первая версия hello() исчезла:", e)

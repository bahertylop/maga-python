"""
Задача 18 (агрегация и ассоциация). В автосалоне покупатель оформляет
автомобиль — но автомобиль не принадлежит покупателю до момента продажи, он
существует отдельно и принадлежит автосалону. Реализуйте класс Buyer
(покупатель), который содержит список выбранных автомобилей. Автомобили при
этом существуют отдельно от покупателя — это агрегация, а не композиция.
Дополнительно реализуйте ассоциацию: у каждого автомобиля есть ссылка на
Dealership, в котором он продаётся. Продемонстрируйте, что при удалении
покупателя автомобили остаются в салоне. Объясните разницу между
композицией (жёсткая связь, часть не может существовать без целого),
агрегацией (мягкая связь, часть существует отдельно) и ассоциацией (просто
ссылка между независимыми объектами).
"""


class Dealership:
    def __init__(self, name):
        self.name = name
        self.cars = []

    def add_car(self, car):
        self.cars.append(car)

    def show_cars(self):
        print(f"В салоне «{self.name}»: {', '.join(str(c) for c in self.cars)}")


class Car:
    def __init__(self, brand, model, dealership):
        self.brand = brand
        self.model = model
        # АССОЦИАЦИЯ: автомобиль просто «знает», в каком салоне продаётся.
        # Салон создан отдельно, автомобиль им не владеет.
        self.dealership = dealership
        dealership.add_car(self)

    def __str__(self):
        return f"{self.brand} {self.model}"


class Buyer:
    def __init__(self, name):
        self.name = name
        # АГРЕГАЦИЯ: покупатель хранит ссылки на автомобили, но не создаёт
        # их и не владеет ими — они созданы снаружи и живут в салоне.
        self.selected_cars = []

    def select_car(self, car):
        self.selected_cars.append(car)

    def show_selection(self):
        for car in self.selected_cars:
            print(f"{self.name} выбрал {car} (продаётся в «{car.dealership.name}»)")


salon = Dealership("АвтоМир")
camry = Car("Toyota", "Camry", salon)
rio = Car("Kia", "Rio", salon)
x5 = Car("BMW", "X5", salon)

buyer = Buyer("Иван Петров")
buyer.select_car(camry)
buyer.select_car(x5)
buyer.show_selection()

print("\nУдаляем покупателя...")
del buyer

# Автомобили никуда не делись — они по-прежнему в салоне
salon.show_cars()
print("Camry всё ещё существует:", camry, "— салон:", camry.dealership.name)

# Разница между видами связей:
# - КОМПОЗИЦИЯ — жёсткая связь «целое — часть». Целое само создаёт часть,
#   часть не существует без целого и погибает вместе с ним.
#   Пример (задача 8): Car создаёт свой Engine в конструкторе.
# - АГРЕГАЦИЯ — мягкая связь «целое — часть». Целое хранит части, но они
#   созданы снаружи и могут жить отдельно (и даже входить в другие целые).
#   Пример: Buyer хранит выбранные Car; удалили покупателя — машины остались.
# - АССОЦИАЦИЯ — просто ссылка между двумя независимыми объектами без
#   отношения «целое — часть». Пример: Car знает свой Dealership.
#   Это «знает о», а не «состоит из».

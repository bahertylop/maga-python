"""
Задача 14 (свойство @property). В автосалоне важно, чтобы цена автомобиля
была корректной — нельзя допустить отрицательную цену или ноль. Перепишите
класс Car так, чтобы поле price было реализовано через свойство @property.
Проверки: цена должна быть числом (int или float), и она должна быть строго
больше нуля. При нарушении должно выбрасываться исключение ValueError с
понятным сообщением. Покажите, что обращение к car.price работает как к
обычному атрибуту (без скобок), но при этом выполняется проверка:
car.price = -100 → ошибка, car.price = 0 → ошибка, car.price = "abc" →
ошибка, car.price = 2500000 → успех. Объясните, чем @property удобнее
классических геттеров и сеттеров, и что такое «вычисляемый атрибут».
"""


class Car:
    VAT = 0.2  # НДС для вычисляемого атрибута

    def __init__(self, brand, model, price):
        self.brand = brand
        self.model = model
        self.price = price  # даже в конструкторе срабатывает сеттер с проверкой

    @property
    def price(self):
        """Геттер: вызывается при чтении car.price."""
        return self._price

    @price.setter
    def price(self, value):
        """Сеттер: вызывается при записи car.price = value."""
        # bool — подкласс int, но True/False ценой быть не могут
        if isinstance(value, bool) or not isinstance(value, (int, float)):
            raise ValueError(f"Цена должна быть числом, получено: {value!r}")
        if value <= 0:
            raise ValueError(f"Цена должна быть больше нуля, получено: {value}")
        self._price = value

    @property
    def price_with_vat(self):
        """Вычисляемый атрибут: не хранится, а считается при каждом обращении."""
        return round(self._price * (1 + self.VAT))


car = Car("Toyota", "Camry", 2000000)
print("Цена:", car.price)  # без скобок, как обычный атрибут

for bad in (-100, 0, "abc"):
    try:
        car.price = bad
    except ValueError as e:
        print(f"car.price = {bad!r} → ошибка: {e}")

car.price = 2500000
print("car.price = 2500000 → успех, цена:", car.price)
print("Цена с НДС (вычисляемый атрибут):", car.price_with_vat)

# Чем @property удобнее классических геттеров и сеттеров:
# - синтаксис остаётся простым: car.price и car.price = x вместо
#   car.get_price() и car.set_price(x);
# - можно начать с обычного атрибута, а проверку добавить позже, не меняя
#   ни одной строки во внешнем коде — интерфейс класса тот же;
# - проверка срабатывает всегда, включая конструктор, поэтому объект
#   с некорректной ценой создать невозможно.
#
# Вычисляемый атрибут — свойство, значение которого не хранится в объекте,
# а рассчитывается из других полей при каждом обращении (price_with_vat).
# Он всегда актуален: изменили цену — цена с НДС пересчиталась сама.

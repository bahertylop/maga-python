"""
Задача 13 (магические методы __add__ и __len__). В автосалоне есть
выставочные площадки, и иногда нужно объединять их (например, при
расширении салона) или узнавать, сколько машин на площадке. Создайте класс
Showroom (выставочная площадка), в котором хранится список автомобилей.
Реализуйте магический метод __add__ для объединения двух площадок в одну
(возвращается новая площадка со всеми автомобилями) и метод __len__,
возвращающий количество автомобилей на площадке. Продемонстрируйте работу:
создайте две площадки, объедините их через showroom3 = showroom1 +
showroom2 и выведите len(showroom3). Объясните, почему __add__ возвращает
новый объект, а не изменяет существующий, и как магические методы делают
объекты «похожими» на встроенные типы.
"""


class Showroom:
    def __init__(self, name, cars=None):
        self.name = name
        # Копируем список, чтобы площадка не делила его с внешним кодом
        self.cars = list(cars) if cars else []

    def __add__(self, other):
        if not isinstance(other, Showroom):
            return NotImplemented
        # Создаём НОВУЮ площадку, исходные не трогаем
        return Showroom(f"{self.name} + {other.name}", self.cars + other.cars)

    def __len__(self):
        return len(self.cars)

    def __str__(self):
        return f"Площадка «{self.name}»: {', '.join(self.cars)}"


showroom1 = Showroom("Север", ["Toyota Camry", "Kia Rio"])
showroom2 = Showroom("Юг", ["BMW X5", "Lada Vesta", "Haval Jolion"])

showroom3 = showroom1 + showroom2   # вызывается showroom1.__add__(showroom2)

print(showroom1)
print(showroom2)
print(showroom3)
print("len(showroom1) =", len(showroom1))  # 2
print("len(showroom2) =", len(showroom2))  # 3
print("len(showroom3) =", len(showroom3))  # 5

# Почему __add__ возвращает новый объект:
# так ведут себя встроенные типы: 2 + 3 не меняет ни 2, ни 3, а
# [1] + [2] даёт новый список. Если бы «+» изменял левую площадку,
# после showroom3 = showroom1 + showroom2 неожиданно изменилась бы и
# showroom1 — это источник трудноуловимых ошибок. Для изменения «на месте»
# в Python есть отдельный метод __iadd__ (оператор +=).
#
# Как магические методы делают объекты похожими на встроенные типы:
# Python превращает операторы и встроенные функции в вызовы магических
# методов: a + b → a.__add__(b), len(a) → a.__len__(), print(a) → a.__str__().
# Реализовав их, мы позволяем работать со своим классом так же привычно,
# как с числами, строками и списками. Бонус: объект с __len__ при пустом
# списке считается ложным в if — как пустой список.
if not Showroom("Пустая"):
    print("Пустая площадка в условии ведёт себя как False")

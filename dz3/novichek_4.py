"""
Задача 4 (полиморфизм). Автосалон рассчитывает налог для разных типов
транспорта. Создайте классы Sedan, SUV и SportCar, у каждого из которых есть
метод tax(), возвращающий размер налога: для седана — 5000, для
внедорожника — 12000, для спорткара — 25000. Напишите функцию
show_tax(vehicle), которая принимает любой транспорт и выводит размер его
налога. Убедитесь, что функция одинаково работает со всеми тремя типами
объектов, не зная заранее, какой именно объект ей передан. Объясните, как
Python определяет, какой именно метод вызвать, и что такое «утиная
типизация» — детально она разбирается в задаче 30.
"""


class Sedan:
    def tax(self):
        return 5000


class SUV:
    def tax(self):
        return 12000


class SportCar:
    def tax(self):
        return 25000


def show_tax(vehicle):
    # Функция не проверяет тип объекта — ей достаточно, что у него есть
    # метод tax(). Какой именно tax() вызвать, Python решает во время
    # выполнения: берёт класс переданного объекта (type(vehicle)) и ищет
    # метод сначала в нём, затем в его родителях (порядок MRO).
    # Это и есть полиморфизм: один вызов — разное поведение.
    #
    # «Утиная типизация»: «если что-то ходит как утка и крякает как утка,
    # значит, это утка». Python важен не тип объекта, а наличие нужных
    # методов. Классам даже не нужен общий родитель (подробнее — задача 30).
    print(f"{type(vehicle).__name__}: налог {vehicle.tax()} ₽")


for v in (Sedan(), SUV(), SportCar()):
    show_tax(v)

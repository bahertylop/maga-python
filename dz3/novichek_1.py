"""
Задача 1 (создание класса, конструктор, метод). В автосалоне ведётся учёт
автомобилей. Создайте класс Car с полями brand (марка), model (модель) и
price (цена). Реализуйте конструктор __init__, который принимает эти три
значения и сохраняет их в объекте. Добавьте метод info(), который возвращает
строку с информацией об автомобиле в формате: Марка — модель, цена. Создайте
один экземпляр класса, вызовите метод и выведите результат на экран.
Ожидаемый вывод, например: Toyota — Camry, 2 500 000 ₽. В комментариях
поясните, чем класс отличается от объекта и зачем нужен параметр self в
методах.
"""

# Класс — это «чертёж» (шаблон): он описывает, какие поля и методы будут
# у автомобилей, но сам по себе конкретным автомобилем не является.
# Объект (экземпляр) — это конкретный автомобиль, созданный по этому
# чертежу, со своими значениями полей (например, Toyota Camry за 2,5 млн).
# По одному классу можно создать сколько угодно разных объектов.


class Car:
    def __init__(self, brand, model, price):
        # self — ссылка на тот самый объект, который сейчас создаётся
        # (или у которого вызван метод). Через self мы сохраняем данные
        # именно в этот объект, а не в какой-то другой.
        self.brand = brand
        self.model = model
        self.price = price

    def info(self):
        # self нужен и здесь: метод один на весь класс, а self подсказывает,
        # данные какого именно автомобиля использовать.
        # Python передаёт self автоматически: car.info() == Car.info(car).
        price_str = f"{self.price:,}".replace(",", " ")
        return f"{self.brand} — {self.model}, {price_str} ₽"


car = Car("Toyota", "Camry", 2500000)
print(car.info())  # Toyota — Camry, 2 500 000 ₽

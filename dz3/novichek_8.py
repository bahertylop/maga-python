"""
Задача 8 (композиция). У каждого автомобиля есть двигатель — автомобиль не
может существовать без него, и двигатель создаётся вместе с автомобилем.
Создайте класс Engine с методом show(), который выводит строку «Бензиновый
двигатель». Создайте класс Car, который содержит объект класса Engine внутри
себя как поле (композиция) — объект Engine создаётся прямо в конструкторе
автомобиля. Метод show_car() у автомобиля должен выводить модель автомобиля
и вызывать метод show() у его двигателя, демонстрируя, что автомобиль
«владеет» своим двигателем. Объясните, почему это именно композиция, а не
агрегация (разница разбирается в задаче 18).
"""


class Engine:
    def show(self):
        print("Бензиновый двигатель")


class Car:
    def __init__(self, model):
        self.model = model
        # Двигатель создаётся ВНУТРИ конструктора автомобиля.
        # Снаружи его не передают — автомобиль сам его создаёт и им владеет.
        self.engine = Engine()

    def show_car(self):
        print(f"Автомобиль: {self.model}")
        self.engine.show()  # автомобиль делегирует работу своему двигателю


car = Car("Toyota Camry")
car.show_car()

# Почему это композиция, а не агрегация:
# - Композиция — это сильная связь «часть — целое»: часть создаётся
#   вместе с целым и живёт, пока живёт целое. Здесь Engine создаётся
#   в конструкторе Car, и никто снаружи не держит ссылку на этот двигатель.
#   Удалим автомобиль — исчезнет и его двигатель.
# - Агрегация — слабая связь: объект создаётся отдельно и передаётся
#   внутрь (например, Car(model, engine)). Тогда часть может существовать
#   независимо и даже принадлежать другому объекту (подробнее — задача 18).

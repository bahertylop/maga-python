"""
Задача 11 (магические методы __str__ и __repr__). Автомобили часто выводят на
экран — в каталогах, прайс-листах, отчётах. По умолчанию print(car) выводит
нечитаемый адрес объекта в памяти, что неудобно. Добавьте в класс Car
магический метод __str__, который возвращает строку вида
«Автомобиль "Toyota Camry" — 2 500 000 ₽». Убедитесь, что при вызове
print(car) выводится именно эта строка. Дополнительно реализуйте метод
__repr__, который возвращает техническое представление объекта, например
Car('Toyota', 'Camry', 2500000) — оно используется при выводе списка
автомобилей и в отладчике. Поясните разницу между __str__ и __repr__ и когда
какой используется: __str__ — для человека, __repr__ — для разработчика.
"""


class Car:
    def __init__(self, brand, model, price):
        self.brand = brand
        self.model = model
        self.price = price

    def __str__(self):
        # Для человека: красиво и понятно. Используется в print() и str().
        price_str = f"{self.price:,}".replace(",", " ")
        return f'Автомобиль "{self.brand} {self.model}" — {price_str} ₽'

    def __repr__(self):
        # Для разработчика: однозначно и технически точно. В идеале по этой
        # строке можно заново создать такой же объект.
        # Используется в консоли, отладчике и при выводе списков/словарей.
        return f"Car({self.brand!r}, {self.model!r}, {self.price!r})"


class CarWithoutStr:
    def __init__(self, brand):
        self.brand = brand


print("Без __str__:", CarWithoutStr("Toyota"))  # нечитаемый адрес в памяти

car = Car("Toyota", "Camry", 2500000)
print(car)          # вызывается __str__
print(repr(car))    # вызывается __repr__

cars = [car, Car("Kia", "Rio", 1800000)]
print(cars)         # у элементов списка всегда вызывается __repr__

# Разница:
# - __str__ — «человеческое» представление: для пользователей, отчётов,
#   прайс-листов. Вызывается в print(obj), str(obj), f"{obj}".
# - __repr__ — «техническое» представление: для разработчика. Вызывается
#   в repr(obj), в интерактивной консоли, в отладчике и внутри коллекций.
# - Если __str__ не определён, Python использует __repr__.
#   Поэтому, если реализовывать только один метод, лучше __repr__.

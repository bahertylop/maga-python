"""
Задача 16 (классовые vs экземплярные атрибуты). Автосалону нужно вести общий
счётчик всех автомобилей — сколько всего автомобилей зарегистрировано в
системе. Добавьте в класс Car классовый атрибут count = 0, который
увеличивается в конструкторе при создании каждого нового автомобиля.
Убедитесь, что count общий для всех объектов класса, а не для отдельного
экземпляра: создайте несколько автомобилей и выведите Car.count.
Дополнительно покажите, что если попытаться изменить count через экземпляр
(car.count = 100), создастся отдельный атрибут экземпляра, а классовый
останется прежним. Объясните разницу между классовыми и экземплярными
атрибутами и в каком порядке Python ищет атрибут при обращении obj.attr.
"""


class Car:
    count = 0  # классовый атрибут — один на весь класс

    def __init__(self, brand, model):
        self.brand = brand  # экземплярные атрибуты — свои у каждого объекта
        self.model = model
        # Увеличиваем именно через Car.count (не self.count += 1!):
        # self.count += 1 создал бы атрибут экземпляра, и общий счётчик не изменился бы.
        Car.count += 1


car1 = Car("Toyota", "Camry")
car2 = Car("Kia", "Rio")
car3 = Car("BMW", "X5")

print("Car.count  =", Car.count)   # 3
print("car1.count =", car1.count)  # 3 — читается из класса
print("car3.count =", car3.count)  # 3 — у всех одно и то же значение

# Попытка изменить счётчик через экземпляр
car1.count = 100
print("\nПосле car1.count = 100:")
print("car1.count =", car1.count)  # 100 — новый атрибут экземпляра
print("car2.count =", car2.count)  # 3   — по-прежнему классовый
print("Car.count  =", Car.count)   # 3   — классовый не изменился
print("car1.__dict__ =", car1.__dict__)  # count теперь лежит в самом объекте
print("car2.__dict__ =", car2.__dict__)  # а здесь его нет

del car1.count  # удаляем атрибут экземпляра — снова «видим» классовый
print("После del car1.count: car1.count =", car1.count)  # 3

# Разница:
# - Классовый атрибут объявлен в теле класса и хранится в Car.__dict__.
#   Он общий для всех объектов: счётчики, константы, настройки.
# - Экземплярный атрибут создаётся через self.attr = ... и хранится
#   в obj.__dict__. У каждого объекта своё значение: марка, модель.
#
# Порядок поиска obj.attr при чтении:
# 1. словарь самого объекта (obj.__dict__);
# 2. словарь класса (type(obj).__dict__);
# 3. словари родительских классов по порядку MRO;
# 4. если нигде нет — AttributeError.
# (Точнее, ещё раньше проверяются «дескрипторы данных» класса, например
#  @property, но для обычных атрибутов достаточно этой схемы.)
# При ЗАПИСИ obj.attr = value Python всегда пишет в obj.__dict__,
# поэтому car1.count = 100 создал новый атрибут экземпляра.

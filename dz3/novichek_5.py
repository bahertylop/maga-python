"""
Задача 5 (модификаторы доступа). Создайте класс SalesManager (менеджер по
продажам), в котором есть три поля: name — публичное (доступно всем),
_department — защищённое (отдел продаж, доступно внутри класса и
наследникам), __commission — приватное (процент комиссии, доступен только
внутри класса). Продемонстрируйте обращение к каждому из полей извне класса:
к name — свободно, к _department — можно, но не рекомендуется, к
__commission — вызовет ошибку. Дополнительно покажите доступ к приватному
полю через name mangling (_SalesManager__commission) — так вы увидите, что
«приватность» в Python условна. Объясните в комментариях, почему приватное
поле защищает данные сотрудника и как это связано с принципом инкапсуляции.
"""


class SalesManager:
    def __init__(self, name, department, commission):
        self.name = name               # публичное поле
        self._department = department  # защищённое (договорённость: «только для своих»)
        self.__commission = commission  # приватное (имя искажается Python)

    def get_commission_info(self):
        # Внутри класса к приватному полю можно обращаться свободно.
        return f"Комиссия {self.name}: {self.__commission}%"


manager = SalesManager("Иван Петров", "Отдел продаж", 3.5)

# 1. Публичное поле — свободный доступ
print("name:", manager.name)

# 2. Защищённое поле — технически доступно, но одно подчёркивание говорит:
#    «это внутренняя деталь, снаружи лучше не трогать»
print("_department:", manager._department)

# 3. Приватное поле — прямой доступ вызывает ошибку
try:
    print(manager.__commission)
except AttributeError as e:
    print("__commission: ошибка AttributeError —", e)

# Правильный способ — через метод класса
print(manager.get_commission_info())

# Name mangling: Python хранит поле под именем _SalesManager__commission,
# поэтому «приватность» условна — обойти её можно, если очень захотеть.
print("Через name mangling:", manager._SalesManager__commission)

# Почему приватное поле защищает данные сотрудника:
# процент комиссии — чувствительные данные, от которых зависит зарплата.
# Если поле открыто, любой код может случайно или намеренно изменить его
# (manager.commission = 100). Скрывая поле, класс сам решает, как с ним
# работать: можно добавить методы с проверками и правами доступа.
# В этом и состоит инкапсуляция — объединение данных и методов работы с ними
# в одном классе и сокрытие внутреннего устройства от внешнего кода.

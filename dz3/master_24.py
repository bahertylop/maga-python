"""
Задача 24 (паттерн Singleton). Реализуйте класс CarCatalog через паттерн
«Одиночка» двумя способами: через метакласс (как в задаче 23) и через
переопределение метода __new__ (без метакласса). Сравните оба подхода:
метакласс работает автоматически для наследников, но сложнее для понимания;
__new__ проще читать, но приходится переопределять в каждом классе.
Объясните, в каких случаях паттерн Singleton полезен (кэш, конфиг, логгер), а
в каких — вреден (например, усложняет тестирование, скрывает зависимости и
мешает подменять реализации).
"""


# ===================== Способ 1: метакласс =====================
class SingletonMeta(type):
    _instances = {}

    def __call__(cls, *args, **kwargs):
        if cls not in cls._instances:
            cls._instances[cls] = super().__call__(*args, **kwargs)
        return cls._instances[cls]


class CarCatalogMeta(metaclass=SingletonMeta):
    def __init__(self):
        self.cars = []


class TruckCatalogMeta(CarCatalogMeta):  # наследник — Singleton автоматически,
    pass                                 # причём со СВОИМ единственным экземпляром


# ===================== Способ 2: __new__ =====================
class CarCatalogNew:
    _instance = None

    def __new__(cls, *args, **kwargs):
        # __new__ создаёт объект, __init__ его настраивает.
        # Перехватываем создание: если объект уже есть — отдаём его.
        if cls._instance is None:
            cls._instance = super().__new__(cls)
        return cls._instance

    def __init__(self):
        # Подвох: __init__ вызывается при КАЖДОМ CarCatalogNew(),
        # даже если __new__ вернул старый объект. Без защиты список
        # машин обнулялся бы при каждом вызове.
        if getattr(self, "_initialized", False):
            return
        self.cars = []
        self._initialized = True


class TruckCatalogNew(CarCatalogNew):
    pass


def demo(title, catalog_cls, sub_cls):
    print(f"--- {title} ---")
    a = catalog_cls()
    a.cars.append("Toyota Camry")
    b = catalog_cls()
    print("a is b:", a is b, "| каталог через b:", b.cars)
    t = sub_cls()
    print(f"{sub_cls.__name__}() is {catalog_cls.__name__}():", t is a,
          "| t.cars:", t.cars)


demo("Через метакласс", CarCatalogMeta, TruckCatalogMeta)
demo("Через __new__", CarCatalogNew, TruckCatalogNew)

# Обратите внимание на наследников:
# - с метаклассом TruckCatalogMeta получил СВОЙ отдельный экземпляр
#   (словарь _instances хранит по объекту на класс) — поведение логичное;
# - с __new__ TruckCatalogNew() вернул объект CarCatalogNew, потому что
#   _instance уже был заполнен у родителя и унаследовался. Чтобы это
#   исправить, у наследника приходится заново объявлять _instance = None
#   (или хранить экземпляры в словаре по cls) — то есть дорабатывать
#   каждый класс вручную.
#
# Сравнение:
# Метакласс                          | __new__
# -----------------------------------|------------------------------------
# + работает для наследников сам     | + проще читать, без «магии»
# + __init__ не вызывается повторно  | − __init__ вызывается при каждом
# − сложнее для понимания            |   вызове, нужна защита _initialized
# − конфликтует с другими            | − логику повторяют в каждом классе,
#   метаклассами (например, ABCMeta) |   наследники требуют доработки
#
# Когда Singleton полезен:
# - конфигурация приложения — настройки читаются один раз и одинаковы везде;
# - логгер — все части программы пишут в один журнал;
# - кэш — общий для всех, иначе каждый держал бы свою копию данных;
# - пул соединений с базой данных, общий реестр/каталог.
#
# Когда вреден:
# - усложняет тестирование: состояние сохраняется между тестами, и один тест
#   может «испачкать» данные другого; объект сложно пересоздать «с нуля»;
# - скрывает зависимости: класс достаёт CarCatalog() откуда угодно, и по
#   его конструктору не видно, что он от каталога зависит;
# - мешает подменять реализации: в тесте трудно подсунуть фейковый каталог
#   вместо настоящего;
# - по сути это глобальная переменная — со всеми её минусами, включая
#   проблемы при многопоточности (без блокировки два потока могут создать
#   два экземпляра).
# Часто лучше создать один объект в начале программы и явно передавать его
# туда, где он нужен (внедрение зависимостей). А в Python простой
# «одиночкой» служит модуль: он импортируется один раз.
